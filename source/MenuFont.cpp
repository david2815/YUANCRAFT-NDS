const char* const* MenuFont::glyphRows(char c) { const Glyph* g = find(c); return g ? g->rows : nullptr; }

int MenuFont::advance(int scale) { return scale <= 1 ? 5 : 4 * scale + 2; }

int MenuFont::width(const char* text, int scale) {
    const int n = (int)strlen(text);
    if (n == 0) return 0;
    return n * advance(scale) - (scale <= 1 ? 1 : 2);
}

int MenuFont::scaleFor(int len) { return len <= 12 ? 2 : 1; }

void MenuFont::draw16(u16* fb, const char* text, int x, int y, int scale, u16 color) {
    for (; *text; text++, x += advance(scale)) {
        const Glyph* g = find(*text);
        if (!g) continue;
        for (int r = 0; r < 6; r++)
            for (int c = 0; c < 4; c++)
                if (g->rows[r][c] == '#')
                    for (int sy = 0; sy < scale; sy++)
                        for (int sx = 0; sx < scale; sx++)
                            px16(fb, x + c * scale + sx, y + r * scale + sy, color);
    }
}

void MenuFont::fill16(u16* fb, int x0, int y0, int x1, int y1, u16 color) {
    for (int y = y0; y <= y1; y++)
        for (int x = x0; x <= x1; x++) px16(fb, x, y, color);
}


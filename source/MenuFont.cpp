    const int GLYPH_COUNT = (int)(sizeof(GLYPHS) / sizeof(GLYPHS[0]));

    const Glyph* find(char c) {
        for (int i = 0; i < GLYPH_COUNT; i++) if (GLYPHS[i].c == c) return &GLYPHS[i];
        return nullptr;   // caracter sin glifo: se deja el hueco
    }

    inline void px8(u16* vram, int x, int y, u8 idx) {
        if (x < 0 || x >= 256 || y < 0 || y >= 192) return;
        u16* p = &vram[(y * 256 + x) >> 1];
        u16 v = *p;
        if (x & 1) v = (u16)((v & 0x00FF) | ((u16)idx << 8));
        else       v = (u16)((v & 0xFF00) | idx);
        *p = v;
    }

    inline void px16(u16* fb, int x, int y, u16 color) {
        if (x < 0 || x >= 256 || y < 0 || y >= 192) return;
        fb[y * 256 + x] = color;
    }
